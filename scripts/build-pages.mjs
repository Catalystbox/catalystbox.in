import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const base = 'https://www.catalystbox.in';
const source = fs.readFileSync('index.html', 'utf8');
const metadata = JSON.parse(fs.readFileSync('scripts/thinkmap-metadata.json', 'utf8'));
const escape = s => s.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
function element(id) {
  const start = source.search(new RegExp('<div[^>]*id="' + id + '"[^>]*>'));
  if (start < 0) throw new Error('Missing source section ' + id);
  const tags = /<\/?div\b[^>]*>/g; tags.lastIndex = start;
  let depth = 0, m;
  while ((m = tags.exec(source))) {
    depth += m[0].startsWith('</') ? -1 : 1;
    if (!depth) return source.slice(start, tags.lastIndex);
  }
  throw new Error('Unclosed section ' + id);
}
const nav = source.match(/<nav>[\s\S]*?<\/nav>/)[0];
const footer = source.match(/<footer class="cb-footer">[\s\S]*?<\/footer>/)[0];
const symbols = source.match(/<svg class="cb-symbols"[\s\S]*?<\/svg>/)[0];
const styles = [...source.matchAll(/<link[^>]+(?:stylesheet|icon)[^>]*>/g)].map(m => m[0]).join('\n');
const scripts = `<script src="/assets/js/seo.js"></script><script src="/assets/js/script.js"></script><script src="/assets/js/cgeb.js"></script><script src="/assets/js/partnership.js"></script>`;
function page(route, title, description, body, extra = '') {
  body = body.replace(/[ \t]+$/gm, '');
  const url = base + '/' + route + '/';
  fs.mkdirSync(route, { recursive: true });
  fs.writeFileSync(route + '/index.html', `<!-- Generated by scripts/build-pages.mjs; edit source sections or React components. -->
<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${escape(title)}</title><meta name="description" content="${escape(description)}"><link rel="canonical" href="${url}"><meta property="og:title" content="${escape(title)}"><meta property="og:description" content="${escape(description)}"><meta property="og:url" content="${url}"><meta property="og:site_name" content="CatalystBox">${styles}${extra}</head><body class="light-mode ui-refresh cb-static-page"><a class="cb-skip-link" href="#main-content">Skip to content</a>${nav}${symbols}<main id="main-content" tabindex="-1">${body}</main>${footer}${scripts}${route.startsWith('thinkmap') ? '<script src="/assets/js/thinkmap.bundle.js" defer></script>' : ''}</body></html>\n`);
}
for (const [route, id, title, description] of [
  ['school', 'cgeb', 'School Feedback & Education Benchmarking | CatalystBox', 'Explore the proposed CatalystBox school feedback methodology, stakeholder framework, scoring and publication safeguards.'],
  ['higher-education', 'higher-education', 'Higher Education Feedback & Benchmarks | CatalystBox', 'Explore the proposed higher education feedback framework for students, faculty, alumni, recruiters and institutions.'],
  ['partnership', 'partnership', 'Education Partnerships & AI Solutions | CatalystBox', 'Work with CatalystBox on education intelligence, institutional improvement, research and AI solutions.'],
  ['privacy', 'privacy', 'Privacy Policy: Draft for Legal Review | CatalystBox', 'Draft CatalystBox privacy notice covering feedback, enquiries, analytics, retention and privacy requests.'],
  ['governance', 'governance', 'Data Governance: Review Draft | CatalystBox', 'CatalystBox guidance on aggregate reporting, methodology integrity, authorised access and governance review.'],
  ['contact', 'contact', 'Contact CatalystBox', 'Contact CatalystBox about education intelligence, institutional improvement and partnerships.'],
]) {
  let body = element('page-' + id).replace(/class="page\b/, 'class="page active');
  body = body.replace(/<footer\b[\s\S]*?<\/footer>/g, '');
  page(route, title, description, body);
}
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cb-thinkmap-'));
try {
  const file = path.join(tmp, 'render.cjs');
  await build({ stdin: { contents: `import React from 'react'; import {renderToString} from 'react-dom/server'; import {ThinkMapApp} from './thinkmap/entry.jsx'; export function render(initialPath){ return renderToString(React.createElement(ThinkMapApp,{initialPath})); }`, resolveDir: process.cwd(), loader: 'jsx' }, bundle: true, platform: 'node', format: 'cjs', outfile: file });
  const { default: renderer } = await import(pathToFileURL(file));
  const { render } = renderer;
  for (const [key, [title, description]] of Object.entries(metadata)) {
    const route = key === 'thinkmap' ? 'thinkmap' : 'thinkmap/' + key;
    const url = base + '/' + route + '/';
    const crumbs = [{ '@type': 'ListItem', position: 1, name: 'Home', item: base + '/' }, { '@type': 'ListItem', position: 2, name: 'ThinkMap', item: base + '/thinkmap/' }];
    if (key !== 'thinkmap') crumbs.push({ '@type': 'ListItem', position: 3, name: title.split(' |')[0], item: url });
    const schema = `<script type="application/ld+json">${JSON.stringify({ '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: crumbs })}</script>`;
    const related = Object.entries(metadata).filter(([k]) => k !== key).map(([k, [name]]) => `<a href="/thinkmap/${k === 'thinkmap' ? '' : k + '/'}">${escape(name.split(' |')[0])}</a>`).join(' ');
    // The wording below is already present on the hub; calculator content is rendered unchanged.
    page(route, title, description, `<div class="page active" id="page-thinkmap"><div id="thinkmap-root">${render('/' + route + '/')}</div><section class="cb-static-intro" id="how-it-works"><h2>How to use this tool</h2><p>${escape(description)}</p><p>These tools are illustrative starting points for reflection, not forecasts, diagnoses or promises.</p></section><div role="navigation" class="cb-related cb-wrap" aria-label="Related ThinkMap tools">${related}</div></div>`, schema);
  }
} finally {
  const relative = path.relative(fs.realpathSync(os.tmpdir()), fs.realpathSync(tmp));
  if (path.isAbsolute(relative) || relative.startsWith('..') || !path.basename(tmp).startsWith('cb-thinkmap-')) throw new Error('Unexpected temporary render path');
  fs.rmSync(tmp, { recursive: true, force: true });
}
// Only changed/new content gets today's date; unchanged About keeps its known revision date.
const urls = ['', 'about', 'school', 'higher-education', 'partnership', 'privacy', 'governance', 'contact', ...Object.keys(metadata).map(k => k === 'thinkmap' ? k : 'thinkmap/' + k)];
fs.writeFileSync('sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls.map(r => `  <url><loc>${base}/${r ? r + '/' : ''}</loc><lastmod>2026-10-29</lastmod></url>`).join('\n') + '\n</urlset>\n');
console.log('Rendered ' + urls.length + ' canonical sitemap pages.');
